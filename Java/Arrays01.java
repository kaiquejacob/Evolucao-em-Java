public class Arrays01 {
    static void main(String[] args) {
        int [] idades = new int[3];             // índice vai de 0 a 2
        idades[0] = 21;
        idades[1] = 15;
        idades[2] = 11;
        System.out.println(idades[0]);
        System.out.println(idades[1]);
        System.out.println(idades[2]);
        System.out.println(idades[2]);
        System.out.println(idades[2]);
    }
}
